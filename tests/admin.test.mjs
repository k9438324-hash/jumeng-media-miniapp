import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { resolve } from 'node:path';
import { createAdmin } from '../dist/server/admin.js';
import { createApplication } from '../dist/server/app.js';
import { loadConfig } from '../dist/server/config.js';
import { Content } from '../dist/server/content.js';

test('本机管理台：认证、跨站拦截、草稿发布隔离、上传、学员管理与实时同步',async t=>{
  const dir=mkdtempSync(resolve(tmpdir(),'jumeng-admin-'));
  const config={...loadConfig({}),dbPath:resolve(dir,'db.sqlite'),port:0};
  const admin=createAdmin(config,'test-admin-key');
  const app=createApplication(config,async(_m,_c,_s,onText)=>onText('完成'));
  await new Promise(r=>admin.server.listen(0,'127.0.0.1',r));
  await new Promise(r=>app.server.listen(0,'127.0.0.1',r));
  const base='http://127.0.0.1:'+admin.server.address().port,api='http://127.0.0.1:'+app.server.address().port;
  t.after(async()=>{await admin.close();await app.shutdown();rmSync(dir,{recursive:true,force:true});});
  async function request(path,method='GET',data,headers={}) {
    const r=await fetch(base+path,{method,headers:{Authorization:'Bearer test-admin-key','Content-Type':'application/json',...headers},body:data===undefined?undefined:JSON.stringify(data)});
    return {status:r.status,data:await r.json()};
  }
  assert.equal((await request('/api/courses','GET',undefined,{Authorization:''})).status,401);
  assert.equal((await request('/api/courses','GET',undefined,{Origin:'https://attacker.invalid'})).status,403);
  const login=await (await fetch(api+'/auth/login',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({deviceId:'admin-test-device'})})).json();
  const headers={Authorization:'Bearer '+login.token,'Content-Type':'application/json'};
  const seed=(await request('/api/courses')).data.items;
  const lesson=structuredClone(seed[0].lesson);lesson.name='新课程测试';lesson.file='';lesson.shots.forEach(s=>{s.clip='';s.clipPoster='';s.image='';});
  const saved=await request('/api/courses','POST',{id:0,category:'measure',lesson});assert.equal(saved.status,200);
  const id=saved.data.id;
  let studentCourse=await (await fetch(api+'/course',{headers})).json();assert.ok(!studentCourse.lessons.some(l=>l.id===id));
  assert.equal((await request('/api/courses/'+id+'/publish','POST',{})).status,200);
  studentCourse=await (await fetch(api+'/course',{headers})).json();assert.equal(studentCourse.lessons.at(-1).name,'新课程测试');
  saved.data.name='未发布的修改';await request('/api/courses','POST',{id,category:'case',lesson:saved.data});
  studentCourse=await (await fetch(api+'/course',{headers})).json();assert.equal(studentCourse.lessons.find(l=>l.id===id).name,'新课程测试');
  assert.ok(studentCourse.categories.find(c=>c.id==='measure').lessonIds.includes(id));
  await request('/api/courses/'+id+'/unpublish','POST',{});
  assert.ok(!new Content(admin.store.db).course().lessons.some(l=>l.id===id));
  assert.equal((await request('/api/courses','POST',{category:'bad',lesson})).status,400);
  const incomplete=structuredClone(lesson);incomplete.shots[0].logic='';
  const draft=await request('/api/courses','POST',{category:'measure',lesson:incomplete});
  assert.equal((await request('/api/courses/'+draft.data.id+'/publish','POST',{})).status,400);
  const badUpload=await fetch(base+'/api/upload',{method:'POST',headers:{Authorization:'Bearer test-admin-key','Content-Type':'video/mp4'},body:'not a video'});assert.equal(badUpload.status,400);
  const video=Buffer.concat([Buffer.from([0,0,0,24]),Buffer.from('ftypisom'),Buffer.alloc(32)]);
  const upload=await fetch(base+'/api/upload',{method:'POST',headers:{Authorization:'Bearer test-admin-key','Content-Type':'video/mp4'},body:video});assert.equal(upload.status,200);const media=await upload.json();
  const withMedia=structuredClone(lesson);withMedia.file=media.key;
  const mediaDraft=await request('/api/courses','POST',{category:'measure',lesson:withMedia});
  assert.equal((await fetch(api+'/media/'+media.key)).status,404);
  await request('/api/courses/'+mediaDraft.data.id+'/publish','POST',{});
  const played=await fetch(api+'/media/'+media.key,{headers:{Range:'bytes=0-7'}});assert.equal(played.status,206);assert.equal((await played.arrayBuffer()).byteLength,8);
  const registered=await request('/api/students','POST',{kind:'mock',identity:'admin-test-device',label:'测试学员'});assert.equal(registered.status,200);
  const owner=registered.data.owner,route='/api/students/'+owner;
  assert.equal((await request(route+'/grant','POST',{days:0,quota:10,label:'补额'})).status,400);
  await request(route+'/grant','POST',{days:30,quota:10,label:'首次开通'});
  await request(route+'/grant','POST',{days:0,quota:5,label:'只补额'});
  const before=admin.store.membership(owner).expiresAt;
  await request(route+'/grant','POST',{days:1,quota:0,label:'只续期'});
  assert.equal(admin.store.membership(owner).expiresAt,before+86400000);
  let account=await (await fetch(api+'/account',{headers})).json();assert.equal(account.remaining,15);
  const listed=(await request('/api/students')).data.items.find(s=>s.owner===owner);assert.equal(listed.grants.length,3);assert.equal(listed.label,'测试学员');
  await request(route+'/enabled','POST',{enabled:false});assert.equal((await fetch(api+'/account',{headers})).status,403);
  await request(route+'/enabled','POST',{enabled:true});assert.equal((await fetch(api+'/account',{headers})).status,200);
});
